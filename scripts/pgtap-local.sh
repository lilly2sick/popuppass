#!/bin/sh
# Reproduce the Supabase pgTAP run without docker.
#
# Downloads an embedded Postgres (npm), builds pgTAP from source, starts a
# throwaway server, applies supabase/migrations on top of minimal role/auth/
# storage stubs (scripts/pgtap-local/stub.sql) and runs supabase/tests/*_test.sql.
# This is a local stand-in. Real CI uses `supabase db reset` and `supabase test db`.
#
# Needs: node, npm, git, make, gcc, perl. Must not run as root (postgres refuses);
# when started as root the script re-runs itself as PGTAP_USER (default ecs-user).
#
# Usage: scripts/pgtap-local.sh   (cache dir: $PGTAP_HOME, default .pgtap-local)
set -eu

REPO=$(cd "$(dirname "$0")/.." && pwd)
HOME_DIR=${PGTAP_HOME:-$REPO/.pgtap-local}
PGTAP_REF=${PGTAP_REF:-v1.3.3}
PORT=${PGPORT:-54329}

if [ "$(id -u)" = 0 ]; then
  u=${PGTAP_USER:-ecs-user}
  mkdir -p "$HOME_DIR" && chown -R "$u" "$HOME_DIR"
  exec su "$u" -c "PGTAP_HOME='$HOME_DIR' PGTAP_REF='$PGTAP_REF' PGPORT='$PORT' '$0'"
fi

mkdir -p "$HOME_DIR"
cd "$HOME_DIR"
export npm_config_cache="$HOME_DIR/.npm-cache"

if [ ! -d node_modules/@embedded-postgres ]; then
  [ -f package.json ] || echo '{"private":true}' > package.json
  npm install --no-audit --no-fund @embedded-postgres/linux-x64 pg
fi
NATIVE=$(echo "$HOME_DIR"/node_modules/@embedded-postgres/*/native)
BIN=$NATIVE/bin

if [ ! -f pgtap.sql ]; then
  [ -d pgtap-src ] || git clone --depth 1 --branch "$PGTAP_REF" https://github.com/theory/pgtap.git pgtap-src
  # pgTAP's sql/pgtap.sql is plain SQL generated by make; a fake pg_config avoids a full server install.
  cat > pg_config <<CFG
#!/bin/sh
case "\$1" in
  --pgxs) echo $NATIVE/lib/postgresql/pgxs/src/makefiles/pgxs.mk ;;
  --version) echo "PostgreSQL 18.0" ;;
  --bindir) echo $BIN ;;
  --sharedir) echo $NATIVE/share/postgresql ;;
  --libdir|--pkglibdir) echo $NATIVE/lib/postgresql ;;
  --includedir|--includedir-server|--pkgincludedir) echo $NATIVE/include ;;
  --cc) echo gcc ;;
  *) echo "" ;;
esac
CFG
  chmod +x pg_config
  (cd pgtap-src && make PG_CONFIG="$HOME_DIR/pg_config" sql/pgtap.sql)
  cp pgtap-src/sql/pgtap.sql pgtap.sql
fi

if [ ! -d data ]; then
  "$BIN/initdb" -D data -U postgres --auth=trust >/dev/null
fi
mkdir -p run
"$BIN/pg_ctl" -D data -o "-p $PORT -k $HOME_DIR/run -c listen_addresses=127.0.0.1" -l run/log -w start >/dev/null
trap '"$BIN/pg_ctl" -D data -m fast stop >/dev/null' EXIT

PGPORT=$PORT PGTAP_SQL="$HOME_DIR/pgtap.sql" NODE_PATH="$HOME_DIR/node_modules" \
  node "$REPO/scripts/pgtap-local/run.js"
